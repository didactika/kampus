//! The widget type: a plugin that shows something on a page arranged as a grid, such as the home or the page of a
//! course. This crate is what every widget plugin builds on: the vocabulary of its declaration, re-exported from the
//! module contract, and the conformance rules it must pass. The plugins themselves live in `plugins/<name>`, one
//! crate each, with their web part in `web/`.

pub mod conformance;
pub mod declaration;

pub use declaration::{
    Cells, Grid, Resize, RowHeight, ValueKind, WidgetDeclaration, WidgetSetting, WidgetSize,
};

/// The name of the type, the prefix of every plugin of it: `widget_<name>`, package `kampus-widget-<name>`.
pub const TYPE: &str = "widget";
