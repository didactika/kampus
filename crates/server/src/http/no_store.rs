//! Answers of the API are never stored by browsers or shared caches unless a handler says otherwise: most of them
//! hold personal data, and a stored copy outlives the session that read it.

use axum::extract::Request;
use axum::http::HeaderValue;
use axum::http::header::CACHE_CONTROL;
use axum::middleware::Next;
use axum::response::Response;

/// Adds `Cache-Control: no-store` to every answer that does not set its own caching.
pub async fn no_store(request: Request, next: Next) -> Response {
    let mut response = next.run(request).await;
    response
        .headers_mut()
        .entry(CACHE_CONTROL)
        .or_insert(HeaderValue::from_static("no-store"));
    response
}
