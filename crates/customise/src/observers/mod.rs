//! The listeners of customisation: rules, which hear every event.

use kampus_module::{EventRun, JobFuture, ListenerDeclaration};

use crate::Customise;

/// The listeners of this module.
pub const LISTENERS: &[ListenerDeclaration] = &[ListenerDeclaration {
    event: kampus_events::ANY,
    name: "rules",
    run: rules,
}];

/// Evaluates the rules an event triggers.
fn rules(run: EventRun<'_>) -> JobFuture<'_> {
    Box::pin(async move {
        let customise = run.services.service::<Customise>()?;
        customise.run_rules(run.event, run.services).await.map(drop)
    })
}
