//! The gate a person passes to enrol themselves: a module that knows what a course requires first, such as
//! the courses that must be completed before it, says what is missing. A teacher who enrols someone does not
//! go through it.

use async_trait::async_trait;
use kampus_access::PrincipalId;
use kampus_common::Result;
use kampus_courses::CourseId;

/// What a person still needs before enrolling themselves in a course.
#[async_trait]
pub trait JoiningGate: Send + Sync {
    /// The courses the person has yet to complete before joining; empty when nothing is missing.
    async fn missing(&self, course: CourseId, account: PrincipalId) -> Result<Vec<CourseId>>;
}
