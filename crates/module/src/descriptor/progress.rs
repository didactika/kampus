//! What an activity type offers to progress: a rule of its own, such as using every attempt of a quiz, that a
//! teacher can require of a course module of that type. The module of the type tells progress, for each
//! person, whether they meet it.

/// A rule of progress an activity type declares.
#[derive(Debug, Clone, Copy)]
pub struct ProgressRuleDeclaration {
    /// `<module>.<rule>`, unique in the build.
    pub code: &'static str,
    /// The activity type whose course modules may require it.
    pub activity_type: &'static str,
    /// What it asks, for the teachers who choose it.
    pub summary: &'static str,
}
