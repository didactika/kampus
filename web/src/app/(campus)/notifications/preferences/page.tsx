/** Where the person chooses how to hear about each type of notification. */

import type { Metadata } from "next";

import { optional } from "../../../../api/server";
import type { Preference } from "../../../../api/types";
import { Preferences } from "../../../../features/notifications/Preferences";
import { requestI18n } from "../../../../i18n/server";

/** The title of the page, in the language of the request. */
export async function generateMetadata(): Promise<Metadata> {
  const { t } = await requestI18n();
  return { title: t("prefs.title") };
}

/** The preferences of the person, read on the server. */
export default async function PreferencesPage() {
  return <Preferences preferences={await optional<Preference[]>("/notify/preferences", [])} />;
}
