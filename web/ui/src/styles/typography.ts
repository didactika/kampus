/** The type scale of the design system, as the declarations of one of its roles. */

import { unsafeCSS, type CSSResult } from "lit";

/** The roles of the type scale, from the largest display to the smallest label. */
export type TypeRole =
  | "display-large"
  | "display-medium"
  | "display-small"
  | "headline-large"
  | "headline-medium"
  | "headline-small"
  | "title-large"
  | "title-medium"
  | "title-small"
  | "body-large"
  | "body-medium"
  | "body-small"
  | "label-large"
  | "label-medium"
  | "label-small";

/** The font declarations of a role of the type scale. */
export function type(role: TypeRole): CSSResult {
  return unsafeCSS(
    `font-family: var(--k-type-${role}-family); font-size: var(--k-type-${role}-size); ` +
      `line-height: var(--k-type-${role}-line-height); font-weight: var(--k-type-${role}-weight); ` +
      `letter-spacing: var(--k-type-${role}-tracking);`,
  );
}
